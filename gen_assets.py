import os, base64

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, 'assets_data.py')
entries = {}

def add(rel):
    full = os.path.join(ROOT, rel)
    if os.path.isfile(full):
        with open(full, 'rb') as f:
            entries[rel.replace('\\', '/')] = base64.b64encode(f.read()).decode('ascii')

add('index.html')
fonts_dir = os.path.join(ROOT, 'fonts')
if os.path.isdir(fonts_dir):
    for name in os.listdir(fonts_dir):
        full = os.path.join(fonts_dir, name)
        if os.path.isfile(full):
            entries['fonts/' + name] = base64.b64encode(open(full, 'rb').read()).decode('ascii')

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('# AUTO-GENERATED by gen_assets.py - do not edit\n')
    f.write('ASSETS = {\n')
    for k, v in entries.items():
        f.write('  %r: %r,\n' % (k, v))
    f.write('}\n')
print('embedded', len(entries), 'file(s) ->', os.path.basename(OUT))
for k in entries:
    print('  ', k)
